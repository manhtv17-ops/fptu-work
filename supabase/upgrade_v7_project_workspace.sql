-- 9) Project activity trigger
create or replace function public.log_project_changes()
returns trigger language plpgsql security definer set search_path=public
as $$
declare v_actor uuid:=auth.uid();
begin
 if tg_op='INSERT' then
   insert into public.project_activity_logs(project_id,actor_id,action,new_value) values(new.id,coalesce(v_actor,new.created_by),'project_created',to_jsonb(new));
   return new;
 end if;
 if old.description is distinct from new.description then insert into public.project_activity_logs(project_id,actor_id,action,old_value,new_value) values(new.id,v_actor,'project_description_changed',jsonb_build_object('description',old.description),jsonb_build_object('description',new.description)); end if;
 if old.due_at is distinct from new.due_at then insert into public.project_activity_logs(project_id,actor_id,action,old_value,new_value) values(new.id,v_actor,'project_deadline_changed',jsonb_build_object('due_at',old.due_at),jsonb_build_object('due_at',new.due_at)); end if;
 if old.status is distinct from new.status then insert into public.project_activity_logs(project_id,actor_id,action,old_value,new_value) values(new.id,v_actor,'project_status_changed',jsonb_build_object('status',old.status),jsonb_build_object('status',new.status)); end if;
 return new;
end $$;
drop trigger if exists trg_project_activity on public.projects;
create trigger trg_project_activity after insert or update on public.projects for each row execute function public.log_project_changes();

-- 10) Invite flow now optionally auto-adds Project membership.
create or replace function public.accept_invitation(p_token text)
returns jsonb
language plpgsql security definer set search_path=public
as $$
declare
  inv public.invitations;
  uid uuid:=auth.uid();
begin
  if uid is null then raise exception 'Not authenticated'; end if;
  select * into inv from public.invitations where token=p_token for update;
  if inv.id is null then raise exception 'Invite not found'; end if;
  if inv.revoked_at is not null then raise exception 'Invite revoked'; end if;
  if inv.expires_at is not null and inv.expires_at<now() then raise exception 'Invite expired'; end if;
  if inv.max_uses is not null and inv.usage_count>=inv.max_uses then raise exception 'Invite limit reached'; end if;

  insert into public.memberships(workspace_id,team_id,user_id,role,status)
  values(inv.workspace_id,inv.team_id,uid,inv.role,'active')
  on conflict(workspace_id,user_id) do update set status='active', team_id=coalesce(excluded.team_id,public.memberships.team_id);

  if inv.project_id is not null then
    insert into public.project_members(project_id,user_id,role_in_project,can_create_task,can_assign_task)
    values(inv.project_id,uid,'member',true,true)
    on conflict(project_id,user_id) do nothing;
  end if;

  insert into public.invitation_uses(invitation_id,user_id) values(inv.id,uid) on conflict do nothing;
  update public.invitations set usage_count=(select count(*) from public.invitation_uses where invitation_id=inv.id) where id=inv.id;
  return jsonb_build_object('workspace_id',inv.workspace_id,'team_id',inv.team_id,'project_id',inv.project_id,'role',inv.role);
end $$;

