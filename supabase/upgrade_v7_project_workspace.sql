-- 7) Helper permission functions (SECURITY DEFINER avoids RLS recursion)
create or replace function public.my_workspace_membership(p_workspace_id uuid)
returns public.memberships
language sql stable security definer set search_path=public
as $$
  select m from public.memberships m
  where m.workspace_id=p_workspace_id and m.user_id=auth.uid() and m.status='active'
  limit 1;
$$;

create or replace function public.can_access_project(p_project_id uuid)
returns boolean
language sql stable security definer set search_path=public
as $$
  select exists(
    select 1 from public.projects p
    left join public.memberships m on m.workspace_id=p.workspace_id and m.user_id=auth.uid() and m.status='active'
    left join public.project_members pm on pm.project_id=p.id and pm.user_id=auth.uid()
    where p.id=p_project_id and (
      m.role='manager'
      or p.lead_id=auth.uid()
      or p.owner_id=auth.uid()
      or pm.user_id=auth.uid()
      or (p.visibility='workspace' and m.user_id is not null)
      or (p.visibility='team' and m.team_id=p.team_id)
    )
  );
$$;

create or replace function public.can_create_project_in_team(p_workspace_id uuid,p_team_id uuid)
returns boolean
language sql stable security definer set search_path=public
as $$
  select exists(
    select 1 from public.memberships m
    where m.workspace_id=p_workspace_id and m.user_id=auth.uid() and m.status='active'
      and (m.role='manager' or (m.role='team_lead' and m.team_id=p_team_id) or m.can_create_project)
  );
$$;

create or replace function public.can_manage_project(p_project_id uuid)
returns boolean
language sql stable security definer set search_path=public
as $$
  select exists(
    select 1 from public.projects p
    left join public.memberships m on m.workspace_id=p.workspace_id and m.user_id=auth.uid() and m.status='active'
    left join public.project_members pm on pm.project_id=p.id and pm.user_id=auth.uid()
    where p.id=p_project_id and (
      m.role='manager' or p.lead_id=auth.uid() or p.owner_id=auth.uid() or pm.role_in_project in ('owner','lead') or pm.can_manage_members
    )
  );
$$;

create or replace function public.can_create_task_in_project(p_project_id uuid)
returns boolean
language sql stable security definer set search_path=public
as $$
  select exists(
    select 1 from public.projects p
    left join public.memberships m on m.workspace_id=p.workspace_id and m.user_id=auth.uid() and m.status='active'
    left join public.project_members pm on pm.project_id=p.id and pm.user_id=auth.uid()
    where p.id=p_project_id and (
      m.role='manager' or (m.role='team_lead' and m.team_id=p.team_id) or pm.can_create_task
    )
  );
$$;

-- Replace the old task-access helper so Project members can collaborate.
create or replace function public.can_access_task(p_task_id uuid)
returns boolean
language sql stable security definer set search_path=public
as $$
  select exists (
    select 1 from public.tasks t
    left join public.memberships m on m.workspace_id=t.workspace_id and m.user_id=auth.uid() and m.status='active'
    left join public.task_watchers w on w.task_id=t.id and w.user_id=auth.uid()
    left join public.project_members pm on pm.project_id=t.project_id and pm.user_id=auth.uid()
    where t.id=p_task_id and (
      m.role='manager' or t.assigner_id=auth.uid() or t.assignee_id=auth.uid() or w.user_id=auth.uid()
      or (m.role='team_lead' and m.team_id=t.team_id) or pm.user_id=auth.uid()
    )
  );
$$;

