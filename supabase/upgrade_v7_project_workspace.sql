-- 12) Backfill project lead/owner for existing projects where possible.
update public.projects p
set lead_id=coalesce(p.lead_id,p.created_by), owner_id=coalesce(p.owner_id,p.created_by), code=coalesce(p.code,upper(left(regexp_replace(p.name,'[^A-Za-z0-9]+','','g'),12)))
where p.lead_id is null or p.owner_id is null or p.code is null;

-- Add current project creators to project_members.
insert into public.project_members(project_id,user_id,role_in_project,can_create_task,can_assign_task,can_review_task,can_manage_members)
select p.id,coalesce(p.lead_id,p.created_by),'lead',true,true,true,true
from public.projects p where coalesce(p.lead_id,p.created_by) is not null
on conflict(project_id,user_id) do nothing;

